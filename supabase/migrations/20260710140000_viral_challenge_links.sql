-- Short, opaque share links that preserve the source race mode without putting
-- player or session identifiers in the URL.
alter table public.friend_challenges
  add column if not exists short_code text,
  add column if not exists challenge_type text not null default 'friend',
  add column if not exists daily_challenge_id uuid references public.daily_challenges(id) on delete set null;

update public.friend_challenges
set short_code = substring(replace(id::text, '-', '') from 1 for 10)
where short_code is null;

alter table public.friend_challenges
  alter column short_code set default substring(replace(gen_random_uuid()::text, '-', '') from 1 for 10),
  alter column short_code set not null;

create unique index if not exists friend_challenges_short_code_idx
  on public.friend_challenges (short_code);

alter table public.friend_challenges
  drop constraint if exists friend_challenges_challenge_type_check;
alter table public.friend_challenges
  add constraint friend_challenges_challenge_type_check
  check (challenge_type in ('daily', 'practice', 'friend'));

create table if not exists public.challenge_link_events (
  id bigint generated by default as identity primary key,
  challenge_id uuid references public.friend_challenges(id) on delete cascade not null,
  event_type text not null check (event_type in ('open', 'start', 'complete')),
  user_id uuid references auth.users(id) on delete set null,
  session_id uuid references public.game_sessions(id) on delete set null,
  created_at timestamptz default now() not null
);

create index if not exists challenge_link_events_funnel_idx
  on public.challenge_link_events (challenge_id, event_type, created_at);
create unique index if not exists challenge_link_completion_once_idx
  on public.challenge_link_events (session_id, event_type)
  where session_id is not null and event_type = 'complete';

alter table public.challenge_link_events enable row level security;
-- No client policies: funnel writes and reads stay server-side and separate
-- from leaderboard RPCs.
